function getSelectedLanguage() {
    return (
        localStorage.getItem("shikshaLanguage") ||
        "en"
    );
}

function getTranslation(key) {
    const language =
        getSelectedLanguage();

    return (
        translations[language]?.[key] ||
        translations.en[key] ||
        key
    );
}

function setSelectedLanguage(language) {
    if (!translations[language]) {
        language = "en";
    }

    localStorage.setItem(
        "shikshaLanguage",
        language
    );

    applyLanguage();

    document.dispatchEvent(
        new Event("languageChanged")
    );
}

function applyLanguage() {
    const language =
        getSelectedLanguage();

    const currentTranslations =
        translations[language] ||
        translations.en;

    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const key =
                element.dataset.i18n;

            if (
                currentTranslations[key]
            ) {
                element.textContent =
                    currentTranslations[key];
            }
        });

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach((element) => {

            const key =
                element.dataset
                    .i18nPlaceholder;

            if (
                currentTranslations[key]
            ) {
                element.placeholder =
                    currentTranslations[key];
            }
        });

    document
        .querySelectorAll(
            "[data-i18n-option]"
        )
        .forEach((element) => {

            const key =
                element.dataset
                    .i18nOption;

            if (
                currentTranslations[key]
            ) {
                element.textContent =
                    currentTranslations[key];
            }
        });

    const languageSelect =
        document.getElementById(
            "languageSelect"
        );

    if (languageSelect) {
        languageSelect.value =
            language;
    }
}

document.addEventListener(
    "DOMContentLoaded",
    function () {

        const languageSelect =
            document.getElementById(
                "languageSelect"
            );

        if (languageSelect) {

            languageSelect.value =
                getSelectedLanguage();

            languageSelect.addEventListener(
                "change",
                function (event) {

                    setSelectedLanguage(
                        event.target.value
                    );
                }
            );
        }

        applyLanguage();
    }
);

